"""Generates the export-forwarding code for a gamecache proxy DLL.

The proxy DLL replaces a system DLL that the game loads from its own folder
(e.g. xinput1_4.dll). Every export of the real DLL gets an assembly stub that
jumps through a pointer table, which gamecache.c fills at load time from the
real DLL in the system directory. No absolute paths are baked into the binary.

Usage:
  python -I gen_proxy.py dump <name>             write proxies/<name>.exports from System32
  python -I gen_proxy.py gen  <name> <outdir>    generate proxy_exports.h + proxy_stubs.asm
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_exports(path):
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsz = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    if struct.unpack_from("<H", data, opt)[0] != 0x20B:
        sys.exit("only 64-bit DLLs are supported")
    sections = []
    for k in range(nsec):
        s = opt + optsz + k * 40
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, s + 8)
        sections.append((va, max(vsize, rsize), raw))

    def off(rva):
        for va, size, raw in sections:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(hex(rva))

    def cstr(o):
        return data[o:data.index(b"\0", o)].decode("ascii")

    e = off(struct.unpack_from("<I", data, opt + 112)[0])
    base, nfuncs, nnames, funcs_rva, names_rva, ords_rva = struct.unpack_from("<IIIIII", data, e + 16)
    named = {}
    for k in range(nnames):
        nm = cstr(off(struct.unpack_from("<I", data, off(names_rva) + 4 * k)[0]))
        named[struct.unpack_from("<H", data, off(ords_rva) + 2 * k)[0]] = nm
    result = []
    for idx in range(nfuncs):
        if struct.unpack_from("<I", data, off(funcs_rva) + 4 * idx)[0]:
            result.append((base + idx, named.get(idx)))
    return result


def dump(name):
    sysdir = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32")
    exports = read_exports(os.path.join(sysdir, name + ".dll"))
    out = os.path.join(ROOT, "proxies", name + ".exports")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as fh:
        fh.write(f"# exports of {name}.dll: <ordinal> <name or - for ordinal-only>\n")
        for ordinal, nm in exports:
            fh.write(f"{ordinal} {nm or '-'}\n")
    print(f"{len(exports)} exports -> {out}")


def gen(name, outdir):
    src = os.path.join(ROOT, "proxies", name + ".exports")
    if not os.path.exists(src):
        sys.exit(f"{src} missing - run: gen_proxy.py dump {name}")
    exports = []
    for line in open(src):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        ordinal, nm = line.split()
        if nm == "DllMain":
            continue  # entry point of the real DLL, never imported
        exports.append((int(ordinal), None if nm == "-" else nm))

    os.makedirs(outdir, exist_ok=True)
    h = [f"/* generated by tools/gen_proxy.py from proxies/{name}.exports - do not edit */",
         f'#define GC_PROXY_DLL L"{name}.dll"',
         f"#define GC_EXPORT_COUNT {len(exports)}",
         "static const char *const gc_export_names[GC_EXPORT_COUNT] = {"]
    for ordinal, nm in exports:
        h.append(f'    "{nm}",' if nm else f"    (const char *)(unsigned long long){ordinal},")
    h.append("};")
    for i, (ordinal, nm) in enumerate(exports):
        if nm:
            h.append(f'#pragma comment(linker, "/export:{nm}=gc_stub_{i},@{ordinal}")')
        else:
            h.append(f'#pragma comment(linker, "/export:__ord{ordinal}=gc_stub_{i},@{ordinal},NONAME")')
    with open(os.path.join(outdir, "proxy_exports.h"), "w", newline="\n") as fh:
        fh.write("\n".join(h) + "\n")

    asm = [f"; generated by tools/gen_proxy.py from proxies/{name}.exports - do not edit",
           "EXTERN gc_real:QWORD", ".code"]
    for i in range(len(exports)):
        asm += [f"gc_stub_{i} PROC", f"    jmp qword ptr [gc_real + {i * 8}]", f"gc_stub_{i} ENDP"]
    asm.append("END")
    with open(os.path.join(outdir, "proxy_stubs.asm"), "w", newline="\n") as fh:
        fh.write("\n".join(asm) + "\n")
    print(f"{len(exports)} forwarded exports -> {outdir}")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 4 and sys.argv[1] == "gen":
        gen(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
